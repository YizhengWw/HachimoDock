// Exercises production panels with isolated mocked IPC, not user data or device services.
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({executablePath:process.env.PET_TEST_BROWSER||'/Applications/360Chrome.app/Contents/MacOS/360Chrome',headless:true});
try{
  const page=await browser.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto((process.env.PET_SERVICES_TEST_URL||'http://127.0.0.1:4192')+'/tests/manual/component-services.html');
  const app=page.locator('.component-app').first(),media=page.locator('.component-media');
  await app.getByRole('button',{name:'朗读 / 停止',exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelector('.component-app__actions button')?.disabled===false);
  assert.equal(await media.getByRole('textbox').isEnabled(),true);
  assert.equal(await page.getByRole('button',{name:/授权|允许联网|确认并启用/}).count(),0);
  let calls=await page.evaluate(()=>window.__componentServiceTest.calls);
  assert(calls.length>=2);assert(calls.every(c=>c.operation==='status'),'mount must not enable, record, play or dispatch');
  await app.getByRole('button',{name:'朗读 / 停止',exact:true}).click();
  await page.waitForFunction(()=>window.__componentServiceTest.calls.some(c=>c.action==='host.speak'));
  assert.equal((await page.evaluate(()=>window.__componentServiceTest.calls)).filter(c=>c.action==='host.speak').length,1);
  await app.getByRole('button',{name:'停用服务（保留本机记录）',exact:true}).click();
  await app.getByRole('button',{name:'重新开启服务',exact:true}).waitFor();
  assert.equal(await app.getByRole('button',{name:'朗读 / 停止',exact:true}).isDisabled(),true);
  // A delayed status from before Disable must not visually re-enable the service.
  await page.evaluate(()=>{window.__componentServiceTest.holdMediaStatus=true;});
  await page.waitForFunction(()=>window.__componentServiceTest.pending!==null);
  await media.getByRole('button',{name:'停用 PC 扩展（保留收藏）',exact:true}).click();
  await media.getByRole('button',{name:'重新开启服务',exact:true}).waitFor();
  assert.equal(await media.getByRole('textbox').isDisabled(),true);
  await page.evaluate(()=>window.__componentServiceTest.pending());
  await page.waitForFunction(()=>window.__componentServiceTest.pending===null);
  assert.equal(await media.getByRole('textbox').isDisabled(),true);
  await app.getByRole('button',{name:'重新开启服务',exact:true}).click();
  await media.getByRole('button',{name:'重新开启服务',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.component-app__actions button')?.disabled===false&&document.querySelector('.component-media input')?.disabled===false);
  const weather=page.getByRole('region',{name:'天气回归应用服务'});
  assert.equal(await weather.getByLabel('城市名称').inputValue(),'上海');
  assert.equal(await weather.getByLabel('常用城市').inputValue(),'1');
  assert.equal(await weather.getByLabel('常用城市').locator('option').count(),13,'city choices must be loaded from package profile');
  await weather.getByLabel('常用城市').selectOption('0');
  await page.waitForFunction(()=>window.__componentServiceTest.calls.some(c=>c.componentId==='test-weather'&&c.operation==='configure'&&c.city?.city==='北京'));
  assert.match(await weather.getByRole('status').innerText(),/北京/);
  await weather.getByText('其他城市 / 自定义坐标',{exact:true}).click();
  await weather.getByLabel('城市名称').fill('自定义测试');await page.waitForTimeout(2300);
  assert.equal(await weather.getByLabel('城市名称').inputValue(),'自定义测试','poll must not overwrite unsaved edits');
  assert.equal(await weather.getByLabel('常用城市').inputValue(),'-1');
  await weather.getByRole('button',{name:'使用 IP 自动城市',exact:true}).click();
  await page.waitForFunction(()=>window.__componentServiceTest.calls.some(c=>c.componentId==='test-weather'&&c.operation==='locate'));
  assert.equal(await weather.getByRole('link',{name:'IP 城市服务说明'}).getAttribute('href'),'https://ipwhois.io/documentation');
  await page.evaluate(()=>{window.__componentServiceTest.weatherFailure='自动识别暂不可用，请手动选城';});
  await page.waitForFunction(()=>[...document.querySelectorAll('[role="status"]')].some(n=>n.textContent.includes('自动识别暂不可用')));
  assert(!/正在自动获取/.test(await weather.getByRole('status').innerText()),'failed geolocation must not remain labelled as pending');
  await page.evaluate(()=>{window.__componentServiceTest.appStatusFailure=true;});
  await app.getByText('状态暂不可用',{exact:true}).waitFor();
  assert.equal(await app.getByRole('button',{name:'朗读 / 停止',exact:true}).isDisabled(),true);
  assert.equal(await app.getByText('已手动停用',{exact:true}).count(),0,'poll failure is not a user disable');
  await page.evaluate(()=>{window.__componentServiceTest.appStatusFailure=false;});
  await page.waitForFunction(()=>document.querySelector('.component-app__actions button')?.disabled===false);
  assert.equal(await app.getByRole('alert').count(),0,'recovered polling clears its transient error');
  const notes=page.getByRole('region',{name:'确认回归应用服务'});
  const convert=notes.getByRole('button',{name:'转为待办',exact:true});
  page.once('dialog',dialog=>dialog.dismiss());await convert.click();
  assert(!(await page.evaluate(()=>window.__componentServiceTest.calls)).some(c=>c.componentId==='test-notes'&&c.action),'cancel cannot dispatch');
  page.once('dialog',dialog=>dialog.accept());await convert.click();
  await page.waitForFunction(()=>window.__componentServiceTest.calls.some(c=>c.componentId==='test-notes'&&c.action));
  const noteCall=(await page.evaluate(()=>window.__componentServiceTest.calls)).find(c=>c.componentId==='test-notes'&&c.action);
  assert.equal(noteCall.confirm,true);assert.equal(noteCall.context,'a'.repeat(64));
  await page.evaluate(()=>{window.__componentServiceTest.notesDisabled=true;});
  await page.waitForFunction(()=>[...document.querySelectorAll('.component-app__actions button')].some(b=>b.textContent==='转为待办'&&b.disabled));
  assert.deepEqual(errors,[]);
  console.log('PASS: default-ready app and media controls; no first-use gate or automatic sensitive action; manual disable/re-enable preserves the UI contract. Mocked IPC only.');
}finally{await browser.close();}
