// Product-owned vector primitives; packages select names, never supply paths/code.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const icons=JSON.parse(fs.readFileSync(path.join(root,'pc/src/component-center/app-icons.json'),'utf8'));
let lines=[],entries=[];
for(const [name,paths] of Object.entries(icons)){
  const start=lines.length;
  for(const points of paths)for(let i=1;i<points.length;i++)lines.push([...points[i-1],...points[i]].map(v=>Math.round(v*2)));
  entries.push(`  {"${name}",${start},${lines.length-start}},`);
}
const header=`// Generated by pc/scripts/build-app-icons.mjs; same geometry as PC.\n#pragma once\n#include <stdint.h>\nstatic const uint8_t pet_app_icon_segments[][4]={\n${lines.map(v=>'  {'+v.join(',')+'},').join('\n')}\n};\nstatic const struct {const char *name;uint16_t start,count;} pet_app_icons[]={\n${entries.join('\n')}\n};\n#define PET_APP_ICON_COUNT ${entries.length}\n`;
const file=path.join(root,'firmware/main/pet_p4_app_icons.h');
if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8')!==header)throw Error('Icon table out of date');}
else fs.writeFileSync(file,header);
