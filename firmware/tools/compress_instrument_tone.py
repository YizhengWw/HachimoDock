"""Reproducible lossless pack of the existing canonical little-endian tone table."""
import argparse
import re
import struct
import zlib
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'main/pet_p4_instrument_tone_packed.h'

def tone_bytes():
    text = (ROOT / 'main/pet_p4_instrument_tone_table.h').read_text()
    body = text.split('static const int16_t pet_instrument_tone_pcm[PET_INSTRUMENT_TONE_SAMPLES]={', 1)[1].split('};', 1)[0]
    values = [int(v) for v in re.findall(r'-?\d+', body)]
    assert len(values) == 8192 and all(-32768 <= v <= 32767 for v in values)
    return struct.pack('<8192h', *values)

def fnv(data):
    value = 2166136261
    for byte in data:
        value = ((value ^ byte) * 16777619) & 0xffffffff
    return value

def header():
    raw = tone_bytes(); packed = zlib.compress(raw, 9)
    assert zlib.decompress(packed) == raw and len(raw) - len(packed) >= 3072
    lines = [', '.join('0x%02x' % n for n in packed[i:i+16]) for i in range(0, len(packed), 16)]
    return ('/* Generated by tools/compress_instrument_tone.py; original PCM stays in tone_table.h.\n'
            ' * zlib level9, canonical LE int16, no synthesis/quantization change. */\n'
            '#pragma once\n#include <stdint.h>\n'
            f'#define PET_INSTRUMENT_TONE_RAW_BYTES {len(raw)}u\n'
            f'#define PET_INSTRUMENT_TONE_PACKED_BYTES {len(packed)}u\n'
            f'#define PET_INSTRUMENT_TONE_FNV UINT32_C(0x{fnv(raw):08x})\n'
            f'#define PET_INSTRUMENT_TONE_ADLER UINT32_C(0x{zlib.adler32(raw):08x})\n'
            'static const uint8_t pet_instrument_tone_packed[PET_INSTRUMENT_TONE_PACKED_BYTES]={\n  '
            + ',\n  '.join(lines) + '\n};\n')

def main():
    p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); args = p.parse_args()
    expected = header()
    if args.check:
        if not DEST.is_file() or DEST.read_text() != expected:
            raise SystemExit('Packed tone data is stale; run tools/compress_instrument_tone.py')
    else:
        DEST.write_text(expected)
    raw = tone_bytes()
    print(f'Lossless tone: {len(raw)} -> {len(zlib.compress(raw,9))} bytes; FNV {fnv(raw):08x}')
if __name__ == '__main__':
    main()
