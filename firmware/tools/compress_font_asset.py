"""Losslessly pack existing licensed glyph bytes, never regenerate a font.
Metrics, mappings and kerning stay in the original C source. No installed font.
"""
import argparse
import hashlib
from pathlib import Path
import re
import zlib
ROOT = Path(__file__).resolve().parents[1]

def bitmap_bytes():
    text = (ROOT / 'main/pet_p4_font_cn.c').read_text()
    matches = re.findall(r'const uint8_t glyph_bitmap\[\] = \{(.*?)\n\};', text, re.S)
    if len(matches) != 1:
        raise ValueError('Expected one unchanged original bitmap')
    body = re.sub(r'/\*.*?\*/', '', matches[0], flags=re.S)
    if re.sub(r'0x[0-9a-fA-F]+|[\s,]', '', body):
        raise ValueError('Unexpected generated bitmap syntax')
    raw = bytes(int(value, 16) for value in re.findall(r'0x[0-9a-fA-F]+', body))
    if len(raw) != 554086:
        raise ValueError('Explicitly review a changed font before repacking')
    return raw

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw = bitmap_bytes()
    packed = zlib.compress(raw, 9)
    assert zlib.decompress(packed) == raw
    header = ('/* Generated by tools/compress_font_asset.py from the existing\n'
              ' * MiSans glyph bitmap; retain its source header and license. */\n'
              '#pragma once\n'
              f'#define PET_FONT_BITMAP_BYTES {len(raw)}U\n'
              f'#define PET_FONT_BITMAP_PACKED_BYTES {len(packed)}U\n'
              f'#define PET_FONT_BITMAP_ADLER UINT32_C(0x{zlib.adler32(raw):08x})\n')
    asset = ROOT / 'assets/fonts/pet_cn_16.deflate'
    size_header = ROOT / 'main/pet_p4_font_bitmap_size.h'
    if args.check:
        if not asset.is_file() or asset.read_bytes() != packed or not size_header.is_file() or size_header.read_text() != header:
            raise ValueError('Stale lossless font asset; run tools/compress_font_asset.py')
    else:
        asset.parent.mkdir(parents=True, exist_ok=True)
        asset.write_bytes(packed)
        size_header.write_text(header)
    print(f'font: {len(raw)} -> {len(packed)} bytes; sha256={hashlib.sha256(raw).hexdigest()}; lossless')

if __name__ == '__main__':
    main()
