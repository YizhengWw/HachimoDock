// Deterministic device encoding, not UI screenshots: shared package art + native controls.
import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {resolve,dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {deflateSync} from 'node:zlib';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const out=join(root,'firmware/assets/component-center');
mkdirSync(out,{recursive:true});
const ids=JSON.parse(readFileSync(join(root,'firmware/factory-config.json'))).components.ids;
const records=[], frames=[];
for(const id of ids){
  const pkg=join(root,'pc/builtin-clawpkgs',id);
  const widget=JSON.parse(readFileSync(join(pkg,'runtime/widget.json')));
  const manifest=JSON.parse(readFileSync(join(pkg,'component.json')));
  const image=widget.surface?.images?.find(i=>i.encoding==='jpeg')||widget.surface?.images?.[0];
  const source=image&&join(pkg,image.asset);
  const hasArt=Boolean(source&&existsSync(source));
  const raw=hasArt?execFileSync('ffmpeg',['-v','error','-i',source,'-vf','scale=64:48:flags=lanczos','-frames:v','1','-f','rawvideo','-pix_fmt','rgb565le','pipe:1']):Buffer.alloc(64*48*2);
  if(raw.length!==64*48*2)throw Error('Unexpected thumbnail dimensions');
  frames.push(raw);
  const caption=widget.host||widget.data||widget.media?'连接电脑使用':manifest.kind==='game'?'开始一场小游戏':'随时打开体验';
  records.push(`  {${JSON.stringify(id)}, ${JSON.stringify(caption)}, ${hasArt?'true':'false'}},`);
}
execFileSync('ffmpeg',['-v','error','-y','-i',join(out,'background.png'),'-frames:v','1','-q:v','7','-pix_fmt','yuvj420p',join(out,'center_background.jpg')]);
const packed=deflateSync(Buffer.concat(frames),{level:9});
writeFileSync(join(out,'center_thumbs.deflate'),packed);
writeFileSync(join(out,'catalog.h'),`/* Generated by build_component_center_assets.mjs; source art stays in component packages. */\nstatic const struct { const char *id, *caption; bool art; } center_art_catalog[] = {\n${records.join('\n')}\n};\n#define CENTER_ART_COUNT (sizeof(center_art_catalog)/sizeof(center_art_catalog[0]))\n`);
const bytes=packed.length+readFileSync(join(out,'center_background.jpg')).length;
if(bytes>128*1024)throw Error('Launcher artwork exceeds 128 KiB');
console.log(`${ids.length} entries; launcher artwork ${bytes} bytes`);
