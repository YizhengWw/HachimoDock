"""Build the bounded on-device pinyin candidate table (p4-app-form-v3).

Source: the MIT-licensed default pinyin dictionary shipped with LVGL inside this
repository (managed_components/lvgl__lvgl/src/others/ime/lv_ime_pinyin.c,
`lv_ime_pinyin_def_dict`). Its per-syllable candidate order is preserved; no
other dataset is downloaded. The table is packed as 16-bit BMP code points and a
packed syllable string so the whole header stays under 8 KiB. The same data is
mirrored to JSON for the PC preview and the Python/JS validators.
"""
import argparse
import json
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'managed_components/lvgl__lvgl/src/others/ime/lv_ime_pinyin.c'
HEADER=ROOT/'main/pet_p4_pinyin_table.h'
MIRRORS=[ROOT.parent/'pc/src/component-center/pinyin-table.json',ROOT.parent/'pc/skills/petui/scripts/pinyin-table.json']
BUDGET=8192
T9={c:str(d) for d,letters in enumerate(['','','abc','def','ghi','jkl','mno','pqrs','tuv','wxyz']) for c in letters}
def load():
    text=SOURCE.read_text(encoding='utf-8')
    body=re.search(r'lv_ime_pinyin_def_dict\[\]\s*=\s*\{(.*?)\n\};',text,re.S).group(1)
    pairs=re.findall(r'\{\s*"([a-z]+)"\s*,\s*"([^"]*)"\s*\}',body)
    table=[];seen=set()
    for syllable,chars in pairs:
        if not re.fullmatch(r'[a-z]{1,6}',syllable):raise ValueError(syllable)
        keep=[]
        for ch in chars:
            cp=ord(ch)
            if not 0x4e00<=cp<=0x9fff or ch in keep:continue
            keep.append(ch)
        if not keep:continue  # only glyphs the resident CJK font can draw
        if syllable in seen:raise ValueError('duplicate syllable '+syllable)
        seen.add(syllable);table.append((syllable,''.join(keep)))
    table.sort()
    return table
def render(table):
    syllables=''.join(s+'\0' for s,_ in table)
    chars=[ord(c) for _,cs in table for c in cs]
    offsets=[];total=0
    for _,cs in table:offsets.append(total);total+=len(cs)
    offsets.append(total)
    text_offsets=[];pos=0
    for s,_ in table:text_offsets.append(pos);pos+=len(s)+1
    size=len(syllables)+2*len(chars)+2*len(offsets)+2*len(text_offsets)
    if size>BUDGET:raise ValueError(f'pinyin table {size} B exceeds {BUDGET}')
    def rows(values,per=16):return '\n'.join('  '+','.join(str(v) for v in values[i:i+per])+',' for i in range(0,len(values),per))
    escaped=''.join('\\0' if c=='\0' else c for c in syllables)
    header=('/* Generated by tools/build_pinyin_table.py from the MIT LVGL default pinyin\n'
            ' * dictionary (managed_components/lvgl__lvgl/src/others/ime/lv_ime_pinyin.c).\n'
            ' * Do not edit: rerun the generator. Candidate order per syllable is the\n'
            ' * dictionary order; coverage is the dictionary, not a frequency corpus. */\n'
            '#pragma once\n#include <stdint.h>\n'
            f'#define PET_PINYIN_SYLLABLES {len(table)}U\n#define PET_PINYIN_CHARS {len(chars)}U\n#define PET_PINYIN_TABLE_BYTES {size}U\n'
            f'static const char pet_pinyin_syllables[]="{escaped}";\n'
            f'static const uint16_t pet_pinyin_syllable_text[PET_PINYIN_SYLLABLES]={{\n{rows(text_offsets)}\n}};\n'
            f'static const uint16_t pet_pinyin_syllable_offset[PET_PINYIN_SYLLABLES+1]={{\n{rows(offsets)}\n}};\n'
            f'static const uint16_t pet_pinyin_chars[PET_PINYIN_CHARS]={{\n{rows(chars)}\n}};\n')
    mirror=json.dumps({'source':'lvgl lv_ime_pinyin_def_dict (MIT)','bytes':size,'syllables':[{'pinyin':s,'t9':''.join(T9[c] for c in s),'chars':cs} for s,cs in table]},ensure_ascii=False,separators=(',',':'))+'\n'
    return header,mirror
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    header,mirror=render(load())
    targets=[(HEADER,header)]+[(m,mirror) for m in MIRRORS]
    if args.check:
        stale=[str(p) for p,content in targets if not p.is_file() or p.read_text(encoding='utf-8')!=content]
        if stale:raise SystemExit('stale pinyin table: '+', '.join(stale))
        return
    for p,content in targets:p.parent.mkdir(parents=True,exist_ok=True);p.write_text(content,encoding='utf-8')
if __name__=='__main__':main()
